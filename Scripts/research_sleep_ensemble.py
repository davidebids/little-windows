#!/usr/bin/env python3
"""Walk-forward calibration and expert combination of causal sleep forecasts.

Use only private feature caches and result files generated by the research
benchmark. No personal data or trained parameters are bundled into the app.
"""
import argparse
import json
from pathlib import Path

import numpy as np
from sleep_research_metadata import care_exposure


def weighted_median(values, weights):
    order = np.argsort(values)
    cumulative = np.cumsum(weights[order])
    return float(values[order[np.searchsorted(cumulative, cumulative[-1] / 2)]])


def combine(data, members, policy="soft", calibrate=True, local=True, lookback_days=30, half_life_days=10, correction_limit=30):
    """Past predictions are scored as originally issued, not refitted in hindsight."""
    if correction_limit is not None and (not np.isfinite(correction_limit) or correction_limit < 0):
        raise ValueError("Correction limit must be finite and nonnegative, or None")
    x, y, wakes, available = [data[k] for k in ["X", "y", "wakes", "available"]]
    names = list(data["names"])
    clock = np.mod(np.arctan2(x[:, names.index("clockSin1")], x[:, names.index("clockCos1")]), 2 * np.pi) * 1440 / (2 * np.pi)
    duration = x[:, names.index("lastDuration")]
    adjusted = members.copy()
    output = members[:, 0].copy()
    for i, now in enumerate(wakes):
        train = np.flatnonzero((np.arange(len(y)) < i) & (available <= now) & (wakes >= now - lookback_days * 86400))
        if len(train) < 8:
            continue
        weights = np.exp2(-(now - wakes[train]) / (half_life_days * 86400))
        if local:
            distance = np.abs(clock[train] - clock[i])
            context_weights = np.exp(-np.minimum(distance, 1440 - distance) / 120)
            context_weights *= np.exp(-np.abs(np.log((duration[train] + 10) / (duration[i] + 10))) / .7)
            local_weights = weights * context_weights
            effective = np.sum(local_weights) ** 2 / max(1e-12, np.sum(local_weights ** 2))
            if effective >= 8:
                weights = local_weights
        if calibrate:
            residuals = y[train, None] - members[train]
            corrections = np.array([weighted_median(residuals[:, k], weights) for k in range(members.shape[1])])
            if correction_limit is not None:
                corrections = np.clip(corrections, -correction_limit, correction_limit)
            adjusted[i] = np.clip(members[i] + corrections, 1, 480)
        # Crucially, use each past calibrated forecast as it was issued then.
        errors = np.abs(y[train, None] - adjusted[train])
        risk = np.average(errors + 30 * (errors > 30), weights=weights, axis=0)
        if policy == "best":
            output[i] = adjusted[i, int(np.argmin(risk))]
        elif policy == "median":
            output[i] = np.median(adjusted[i])
        else:
            expert_weights = np.exp(-(risk - np.min(risk)) / 15)
            output[i] = weighted_median(adjusted[i], expert_weights)
    return output


def adaptive_window_predictions(data, members):
    """Each profile supplies its own timeline; only resolved past errors select a window."""
    forecasts = {"window" + str(days): combine(data, members, lookback_days=days, half_life_days=half_life)
                 for days, half_life in [(7, 3), (14, 5), (28, 10), (60, 14)]}
    forecasts["adaptiveWindow"] = combine(data, np.column_stack(list(forecasts.values())),
                                           calibrate=False, lookback_days=14, half_life_days=5)
    return forecasts


def metrics(y, prediction, mask):
    e = np.abs(y[mask] - prediction[mask])
    if not len(e):
        return {"count": 0}
    return dict(count=len(e), mae=float(np.mean(e)), median=float(np.median(e)),
                p90=float(np.quantile(e, .9)), within15=float(np.mean(e <= 15) * 100),
                within30=float(np.mean(e <= 30) * 100))


def learned_combine(data, members, residual=True, context=True, refit_every=24):
    """Learn from prequential expert outputs, never in-sample fitted outputs."""
    from sklearn.ensemble import HistGradientBoostingRegressor
    from sklearn.impute import SimpleImputer
    from sklearn.pipeline import make_pipeline
    from threadpoolctl import threadpool_limits

    y, wakes, available = [data[k] for k in ["y", "wakes", "available"]]
    center = np.median(members, axis=1)
    inputs = np.column_stack([members, np.std(members, axis=1), np.ptp(members, axis=1)])
    if context:
        inputs = np.column_stack([data["X"], inputs])
    target = y - center if residual else y
    output = combine(data, members)
    model, last_fit = None, -refit_every
    with threadpool_limits(limits=1):
        for i, now in enumerate(wakes):
            train = np.flatnonzero((np.arange(len(y)) < i) & (available <= now) & (wakes >= now - 60 * 86400))
            if len(train) < 40:
                continue
            if model is None or i - last_fit >= refit_every:
                model = make_pipeline(SimpleImputer(keep_empty_features=True, add_indicator=True),
                                      HistGradientBoostingRegressor(loss="absolute_error", max_iter=120,
                                                                    max_leaf_nodes=7, min_samples_leaf=10,
                                                                    l2_regularization=10, early_stopping=False,
                                                                    random_state=42))
                model.fit(inputs[train], target[train],
                          histgradientboostingregressor__sample_weight=np.exp2(-(now - wakes[train]) / (14 * 86400)))
                last_fit = i
            prediction = float(model.predict(inputs[i:i + 1])[0])
            output[i] = np.clip(prediction + (center[i] if residual else 0), 1, 480)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--features", type=Path, required=True)
    parser.add_argument("--baseline", type=Path, required=True)
    parser.add_argument("--members", type=Path, nargs="+", default=[])
    parser.add_argument("--baseline-only", action="store_true", help="Ablate local/global calibration without adding experts")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--learned", action="store_true", help="Also evaluate causal learned stacking")
    parser.add_argument("--adaptive-windows", action="store_true", help="Compare sliding histories and causally combine their issued forecasts")
    args = parser.parse_args()
    if args.baseline_only == bool(args.members):
        parser.error("Supply expert members or baseline-only, but not both")
    if args.baseline_only and (args.learned or args.adaptive_windows):
        parser.error("Keep the baseline-only ablation separate from additional variants")
    root = Path(__file__).resolve().parents[1]
    if args.output.resolve().is_relative_to(root):
        parser.error("Keep per-event results outside the repository")
    data = dict(np.load(args.features, allow_pickle=False))
    indices, y = data["indices"], data["y"]
    base = json.loads(args.baseline.read_text())
    rows = {r["index"]: r for r in base["events"]}
    assert set(indices) == set(rows), "Baseline and feature cohorts differ"
    np.testing.assert_allclose(
        [rows[int(i)]["actual"] for i in indices], data["wakes"] + y * 60,
        rtol=0, atol=1e-6, err_msg="Feature cache targets differ from baseline")
    fallback = np.array([(rows[int(i)]["prediction"] - data["wakes"][j]) / 60 for j, i in enumerate(indices)])
    baseline_label = base.get("algorithm", "appBaseline")
    members, labels = [fallback], [baseline_label]
    for path in args.members:
        result = json.loads(path.read_text())
        assert result["audit"]["sourceSHA256"] == base["audit"]["sourceSHA256"]
        assert care_exposure(result) == "completed", "Keep started-care assumptions in a separate analysis"
        for name, events in result["events"].items():
            by_index = {r["index"]: r for r in events}
            assert set(by_index) == set(indices)
            np.testing.assert_allclose([by_index[int(i)]["actual"] for i in indices], y, atol=1e-6)
            members.append(np.array([by_index[int(i)]["prediction"] for i in indices]))
            labels.append(path.stem + "/" + name)
    members = np.column_stack(members)
    day = np.array([rows[int(i)]["context"] == "daytime" for i in indices])
    size = base["audit"]["sleepRows"]
    first_boundary, second_boundary = int(size * .6), int(size * .8)
    masks = dict(all=np.ones(len(y), dtype=bool), daytime=day,
                 development=indices < first_boundary,
                 validation=(indices >= first_boundary) & (indices < second_boundary),
                 finalPeriod=indices >= second_boundary)
    result = dict(audit=dict(sourceSHA256=base["audit"]["sourceSHA256"], members=labels, careExposure="completed",
                            rule="Only labels available at wake; past issued forecasts retained; no random split"),
                  models={baseline_label: {k: metrics(y, fallback, mask) for k, mask in masks.items()}}, events={})
    variants = [("localCalibratedSoft", "soft", True, True), ("localCalibratedBest", "best", True, True),
                ("localRawSoft", "soft", False, True), ("globalCalibratedSoft", "soft", True, False),
                ("calibratedMedian", "median", True, True)]
    if args.baseline_only:
        variants = [("baselineLocalCalibration", "soft", True, True),
                    ("baselineGlobalCalibration", "soft", True, False)]
    for name, policy, calibrate, local in variants:
        p = combine(data, members, policy, calibrate, local)
        result["models"][name] = {k: metrics(y, p, mask) for k, mask in masks.items()}
        result["events"][name] = [dict(index=int(i), actual=float(a), prediction=float(b)) for i, a, b in zip(indices, y, p)]
        print(name, result["models"][name]["all"], flush=True)
    if args.adaptive_windows:
        result["audit"]["windowCandidatesDays"] = [7, 14, 28, 60]
        result["audit"]["windowSelectionLookbackDays"] = 14
        result["audit"]["windowSelectionHalfLifeDays"] = 5
        for name, p in adaptive_window_predictions(data, members).items():
            result["models"][name] = {k: metrics(y, p, mask) for k, mask in masks.items()}
            result["events"][name] = [dict(index=int(i), actual=float(a), prediction=float(b)) for i, a, b in zip(indices, y, p)]
            print(name, result["models"][name]["all"], flush=True)
    if args.learned:
        for name, residual, context in [("learnedResidualContext", True, True),
                                        ("learnedDirectContext", False, True),
                                        ("learnedResidualExperts", True, False)]:
            p = learned_combine(data, members, residual, context)
            result["models"][name] = {k: metrics(y, p, mask) for k, mask in masks.items()}
            result["events"][name] = [dict(index=int(i), actual=float(a), prediction=float(b)) for i, a, b in zip(indices, y, p)]
            print(name, result["models"][name]["all"], flush=True)
    args.output.write_text(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
